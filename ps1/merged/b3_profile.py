"""Milestone B3 native hot-set policy and conservative RAM accounting.

No ROM or private generated bytes are needed to import or test this module.
B2 is retained as a private benchmark/rollback profile. B3 is a candidate,
not proof that a compiled disc meets the stock-performance target.
"""
import os

B2_FILES = frozenset("render tex citydraw model fx physics world draw2d merge ragdoll car ship props s2core space".split())
B3_FILES = B2_FILES | {"marker", "loops", "hudline", "settings"}
B2_CONST = frozenset({"erecip", "sin_table", "rtab", "pb_avg", "font_tiles"})
# Small scalar/palette tables generated by mkpal from the owner's ROM, and
# settings.c scalar tables used by the game-time governor. Their native copies
# are generated privately by the existing compiler pipeline, not committed.
B3_CONST = B2_CONST | frozenset((
    "pb_pmap", "pb_sky", "pb_mesh", "sp_tab",
    "v_target", "v_time", "v_lives", "v_damage", "v_scale", "v_shield",
    "v_grav", "v_bounce", "v_draw", "v_traffic", "v_score", "v_drift",
    "v_steer", "v_cgrav", "v_camd", "v_props", "v_boost",
))
B2_HOT = "render tex citydraw model fx sfport physics world draw2d"


def choose_profile(env=None):
    env = os.environ if env is None else env
    name = env.get("SFNAT_PROFILE", "b3")
    if name not in ("b2", "b3"):
        raise ValueError("SFNAT_PROFILE must be b2 or b3")
    files = B3_FILES if name == "b3" else B2_FILES
    consts = B3_CONST if name == "b3" else B2_CONST
    # Preserve the existing explicit selection mechanism. 'all' is the
    # developer's unrestricted experiment, not an accepted console layout.
    selected = frozenset(env.get("SFNAT_ONLY", " ".join(sorted(files))).split())
    if selected == {"all"}:
        selected = frozenset()
    hot = frozenset(env.get("SFNAT_HOT", B2_HOT).split())
    return name, selected, consts, hot


def align_up(value, alignment):
    if alignment <= 0 or alignment & (alignment - 1):
        raise ValueError("section alignment must be a positive power of two")
    return (value + alignment - 1) & -alignment


def upper_bound(sections):
    """Conservative bytes incl. worst-case section alignment, not just sizes."""
    return sum(size + max(1, alignment) - 1
               for _, _, size, alignment in sections)


def pack_text(sections, caps):
    """Place large text sections first, accounting for each section's alignment."""
    used = {r: 0 for r in caps}
    where = {r: [] for r in (*caps, "R1")}
    ordered = sorted((s for s in sections if s[0].startswith(".text")),
                     key=lambda s: (-s[2], s[0]))
    for name, _, size, alignment in ordered:
        for region, capacity in caps.items():
            end = align_up(used[region], max(4, alignment)) + size
            if end + 16 <= capacity:
                where[region].append(name)
                used[region] = end
                break
        else:
            where["R1"].append(name)
    return where, used


def linked_ram_census(syms, data_size, nat_lo):
    """Exact linked ranges: fail closed on missing symbols or overlaps."""
    if not 0x800a8100 < nat_lo < 0x80119000 or data_size <= 0:
        raise ValueError("invalid native layout parameters")
    ranges = {
        "runtime": (0x80010000, syms["__bss_end"], 0x80028000),
        "runtime_cold": (0x80028040, syms["__rtcold_end"], 0x8002a000),
        "native_R1": (nat_lo, syms["sfn___data_lma"] + data_size, 0x80119000),
        "native_R2": (syms["__doll_start"], syms["__dlbss_end"], 0x8017a000),
        "native_R3": (0x80199000, syms["__sfbss_end"], 0x801b0000),
    }
    result = {}
    for label, (start, end, limit) in ranges.items():
        if not 0x80000000 <= start <= end <= limit <= 0x80200000:
            raise ValueError("linked RAM overlap or invalid range: " + label)
        result[label] = dict(start=start, end=end, limit=limit,
                             used_bytes=end-start, free_bytes=limit-end)
    result["native_stack"] = dict(start=0x80119000, end=0x8011c000,
                                  limit=0x8011c000, reserved_bytes=12288)
    return result
