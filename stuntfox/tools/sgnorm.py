"""Face normals of the city pirates' models (src/sgmodels.h), worked out on this computer by the engine's own
model_init, so the game keeps them in ROM and no RAM.

    python3 tools/sgnorm.py            writes src/sgnorm.inc
    python3 tools/sgnorm.py --check    exits 1 if src/sgnorm.inc is not what model_init gives now
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'src')
INC = os.path.join(SRC, 'sgnorm.inc')
MODELS = ('turret', 'wing', 'hull', 'disc', 'wing_lo', 'hull_lo', 'disc_lo')

DUMP = r'''
#include <stdio.h>
#include "sgmodels.h"
#include "render.h"
Camera cam;
int fog_of(int z) { (void)z; return 0; }
void r_poly(const V3 *v, int n, int color, int key, int bg) { (void)v; (void)n; (void)color; (void)key; (void)bg; }
V3 r_cam(V3 p) { return p; }
V3 r_cam_far(V3 p, int s) { (void)s; return p; }
#define N(a) (sizeof a / sizeof a[0])
static void dump(const char *name, const MVert *v, int nv, const MFace *f, int nf)
{
    N3 nn[40];
    Model m = {v, f, (u8)nv, (u8)nf, 0, nn};
    model_init(&m);
    printf("static const N3 %s_n[%d] = {\n", name, nf);
    for (int i = 0; i < nf; i++)
        printf("%s{%d, %d, %d},%s", i % 6 ? "" : "    ", nn[i].x, nn[i].y, nn[i].z, i % 6 == 5 || i == nf - 1 ? "\n" : " ");
    printf("};\n");
}
#define DO(name) dump(#name, name##_v, N(name##_v), name##_f, N(name##_f))
int main(void)
{
    printf("/* generated by tools/sgnorm.py from sgmodels.h: the face normals model_init gives, in ROM */\n");
    DO(turret); DO(wing); DO(hull); DO(disc); DO(wing_lo); DO(hull_lo); DO(disc_lo);
    return 0;
}
'''


def make():
    tmp = tempfile.mkdtemp(prefix='sgnorm')
    gen = os.path.join(ROOT, 'build', 'gen', 'tables.c')
    if not os.path.exists(gen):
        sys.path.insert(0, HERE)
        import mkassets
        os.makedirs(os.path.dirname(gen), exist_ok=True)
        mkassets.main(gen)
    tab = os.path.join(tmp, 'tables.c')
    open(tab, 'w').write(open(gen).read().replace('"../../src/gba.h"', '"gba.h"'))
    dump, exe = os.path.join(tmp, 'dump.c'), os.path.join(tmp, 'dump')
    open(dump, 'w').write(DUMP)
    subprocess.check_call(['clang', '-O1', '-w', '-fno-builtin', '-ffunction-sections', '-Wl,--gc-sections', '-DMERGE',
                           '-DNORMALS_HOST', '-I' + SRC, dump, tab] +
                          [os.path.join(SRC, f) for f in ('model.c', 'fx.c')] + ['-o', exe])
    return subprocess.run([exe], capture_output=True, text=True, check=True).stdout


if __name__ == '__main__':
    out = make()
    if '--check' in sys.argv:
        ok = os.path.exists(INC) and open(INC).read() == out
        print('sgnorm: %s' % ('src/sgnorm.inc is what model_init gives' if ok else 'src/sgnorm.inc is OUT OF DATE'))
        sys.exit(0 if ok else 1)
    open(INC, 'w').write(out)
    print('sgnorm: wrote', INC)
