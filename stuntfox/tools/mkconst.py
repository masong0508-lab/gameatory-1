"""Tables Stunt Fox works out at start-up, worked out at build time instead, for Payback's little RAM.

model_init works the models' face normals out from their corners, models_init builds the space
ring and the race gate, space_init draws the stars and the asteroids' first turns and spins from a
small random series. Inside Payback that took some 4 KB of the RAM we keep (src/merge.ld, keep), so
build.py runs the same code (src/models.c, src/traffic.c, src/model.c, src/space.c, src/fx.c) on this
computer once, built with NORMALS_HOST, and puts what it gives in ROM (build/gen/consttab.c). Same
integer arithmetic, same numbers: tests/s2/consttab.py compares them with what the old build had in
RAM after start-up.

Output: C source with gen_nbuf (models.c's models in the order it sets them up), gen_tnbuf
(traffic.c's) and gen_hero_n (the player's own); gen_ring_v, gen_ring_f, gen_gate_v, gen_gate_f
(models.c); gen_stars, gen_rock_w, gen_rock_yaw (space.c).

The models themselves (models.c, traffic.c) are ROM const inside Payback too: each takes its normals from gen_nbuf,
gen_tnbuf or gen_hero_n at an offset its source works out, in the order of the lists in main below (a model added
to one needs adding to the other: tests/s2/models.py compares every model with the RAM build's).
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), 'src')

DUMP = r'''
#include <stdio.h>
#include "model.h"
#include "render.h"
#include "traffic.h"
#include "physics.h"
Camera cam;
int fog_of(int z) { (void)z; return 0; }
void r_poly(const V3 *v, int n, int color, int key, int bg) { (void)v; (void)n; (void)color; (void)key; (void)bg; }
V3 r_cam(V3 p) { return p; }
V3 r_cam_far(V3 p, int s) { (void)s; return p; }
extern Model mdl_hero[4][2];
extern MVert ring_v[], gate_v[];
extern MFace ring_f[], gate_f[];
extern V3 stars[], rock_w[];
extern u16 rock_yaw[];
void space_init(void);
V3 station_pos;                    /* (physics.c's, which space_init fills) */
Rock rocks[NROCK];
int nrocks;
static void out(const char *name, const Model *first, const Model *const *all, int nall, int cap)
{
    int n = 0;
    for (int i = 0; i < nall; i++)
        n += all[i]->nf;
    if (n > cap)
        fprintf(stderr, "%s: %d normals, room for %d\n", name, n, cap), n = -1;
    printf("const N3 %s[%d] = {\n", name, n);
    for (int i = 0; i < n; i++)
        printf("%s{%d, %d, %d},%s", i % 6 ? "" : "    ", first->normal[i].x, first->normal[i].y, first->normal[i].z,
               i % 6 == 5 || i == n - 1 ? "\n" : " ");
    printf("};\n");
}
static void verts(const char *name, const MVert *v, int n)
{
    printf("const MVert %s[%d] = {\n", name, n);
    for (int i = 0; i < n; i++)
        printf("%s{%d, %d, %d},%s", i % 4 ? "" : "    ", v[i].x, v[i].y, v[i].z, i % 4 == 3 || i == n - 1 ? "\n" : " ");
    printf("};\n");
}
static void faces(const char *name, const MFace *f, int n)
{
    printf("const MFace %s[%d] = {\n", name, n);
    for (int i = 0; i < n; i++)
        printf("    {%d, %d, %d, {%d, %d, %d, %d, %d, %d}},\n", f[i].n, f[i].mat, f[i].flags, f[i].idx[0], f[i].idx[1],
               f[i].idx[2], f[i].idx[3], f[i].idx[4], f[i].idx[5]);
    printf("};\n");
}
static void vecs(const char *name, const V3 *v, int n)
{
    printf("const V3 %s[%d] = {\n", name, n);
    for (int i = 0; i < n; i++)
        printf("%s{%d, %d, %d},%s", i % 4 ? "" : "    ", v[i].x, v[i].y, v[i].z, i % 4 == 3 || i == n - 1 ? "\n" : " ");
    printf("};\n");
}
int main(void)
{
    models_init();
    traffic_init();
    space_init();
    const Model *m[] = {&mdl_car, &mdl_arwing, &mdl_hub, &mdl_ring, &mdl_rock, &mdl_ped, &mdl_heli, &mdl_bay,
                        &mdl_raider, &mdl_carrier, &mdl_pod, &mdl_medal, &mdl_crate, &mdl_gate, &mdl_beacon, &mdl_boom};
    const Model *t[] = {&mdl_saloon, &mdl_limo, &mdl_pickup, &mdl_sport, &mdl_van, &mdl_bus, &mdl_tank,
                        &mdl_stand, &mdl_stride_a, &mdl_stride_b, &mdl_punch, &mdl_swim[0], &mdl_swim[1]};
    const Model *h[] = {&mdl_hero[0][0], &mdl_hero[0][1], &mdl_hero[3][1]};   /* (as traffic.c lays them out) */
    printf("/* generated by tools/mkconst.py: what start-up works out, worked out at build time */\n"
           "#include \"../../src/model.h\"\n");
    out("gen_nbuf", m[0], m, sizeof m / sizeof m[0], 200);
    out("gen_tnbuf", t[0], t, sizeof t / sizeof t[0], 400);
    out("gen_hero_n", h[0], h, 3, 1000);
    verts("gen_ring_v", ring_v, 48);
    faces("gen_ring_f", ring_f, 36);
    verts("gen_gate_v", gate_v, 16);
    faces("gen_gate_f", gate_f, 8);
    vecs("gen_stars", stars, 40);
    vecs("gen_rock_w", rock_w, 12);
    printf("const u16 gen_rock_yaw[12] = {");
    for (int i = 0; i < 12; i++)
        printf("%s%d", i ? ", " : "", rock_yaw[i]);
    printf("};\n");
    return 0;
}
'''


def main(out, tables):
    tmp = tempfile.mkdtemp(prefix='mkconst')
    dump, exe = os.path.join(tmp, 'dump.c'), os.path.join(tmp, 'dump')
    open(dump, 'w').write(DUMP)
    t = open(tables).read().replace('"../../src/gba.h"', '"gba.h"')   # (the host's own copy of the tables)
    tab = os.path.join(tmp, 'tables.c')
    open(tab, 'w').write(t)
    subprocess.check_call(['clang', '-O1', '-w', '-fno-builtin', '-ffunction-sections', '-Wl,--gc-sections', '-DMERGE',
                           '-DNORMALS_HOST', '-I' + SRC, dump, tab] +
                          [os.path.join(SRC, f) for f in ('models.c', 'traffic.c', 'model.c', 'space.c', 'fx.c')] + ['-o', exe])
    c = subprocess.run([exe], capture_output=True, text=True, check=True).stdout
    assert '[-1]' not in c, 'mkconst: a buffer is too small'
    open(out, 'w').write(c)
    # the table lengths, for the _Static_asserts that check the models' normals offsets (models.c, traffic.c)
    n = {k.upper(): v for k, v in re.findall(r'const N3 gen_(\w+)\[(\d+)\]', c)}
    with open(os.path.join(os.path.dirname(out), 'constlen.h'), 'w') as f:
        f.write('/* generated by tools/mkconst.py: how many normals each table holds */\n')
        for k in ('NBUF', 'TNBUF', 'HERO_N'):
            f.write('#define GEN_%s%s %s\n' % (k, '' if k.endswith('_N') else '_N', n[k]))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
