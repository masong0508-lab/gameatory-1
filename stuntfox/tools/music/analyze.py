"""Facts about a Payback song for remixers, as Markdown: tempo, key, structure, channels,
samples, hooks (repeated one-bar figures) and chords. Pitches are sounding pitches (each
sample's own tuning measured), 4 rows = 1 beat, 16 rows = 1 bar.

    python3 analyze.py ROM SONG > analysis.md
"""
import sys
from collections import Counter, defaultdict

import numpy as np

import mix
import pbsong

DRUMLIKE = ('kick', 'snare/clap', 'hat/cymbal', 'cymbal/crash', 'percussion', 'break/noise', 'fx/noise')


def mmss(t):
    return '%d:%04.1f' % (int(t // 60), t % 60)


def classify(o):
    """Heuristic role of every sample from its sound and how the song uses it."""
    use = defaultdict(list)
    for e in o.raw_notes:
        use[e.instrument].append(e)
    out = {}
    for k, f in o.features.items():
        ev = use.get(k, [])
        if not ev:
            out[k] = ('unused', {})
            continue
        per = Counter(e.period for e in ev)
        p0 = per.most_common(1)[0][0]
        cen = f['centroid'] * pbsong.NATIVE_PERIOD / p0
        f0p = f['f0'] * pbsong.NATIVE_PERIOD / p0 if f['f0'] else None
        pitched = (len(per) >= 3 and f['pitch_conf'] > 0.5) or (f['looped'] and f['pitch_conf'] > 0.6) or f['chord']
        if f['chord']:
            lab = 'chord sample (%s)' % ' '.join(mix.PC_NAMES[p] for p in f['chord'])
        elif not pitched:
            if cen < 700 and f['decay'] < 0.8 and f['seconds'] < 1.2:
                lab = 'kick'
            elif f['flatness'] > 0.45 and cen > 3500:
                lab = 'cymbal/crash' if f['decay'] > 0.5 else 'hat/cymbal'
            elif f['flatness'] > 0.35 and cen > 900 and f['seconds'] < 1.2:
                lab = 'snare/clap'
            elif f['seconds'] >= 1.2 and not f['looped']:
                lab = 'break/noise'
            elif f['looped'] and f['flatness'] > 0.4:
                lab = 'fx/noise'
            else:
                lab = 'percussion'
        else:
            if f0p and f0p < 140:
                lab = 'bass'
            elif f['looped'] and f['seconds'] > 1.0:
                lab = 'pad/strings'
            elif f['decay'] < 0.35:
                lab = 'pluck/stab/arp'
            else:
                lab = 'lead/synth'
        rows16 = Counter(e.row % 16 for e in ev)
        out[k] = (lab, dict(uses=len(ev), periods=per, centroid_played=cen, f0_played=f0p,
                            channels=Counter(e.channel for e in ev), rows16=rows16))
    return out


def analyze(rom, number):
    o = mix.Original(number, rom)
    s = o.song
    cls = classify(o)
    drums = {k for k, (lab, _) in cls.items() if lab in DRUMLIKE or lab == 'unused'}
    L = []
    w = L.append
    key = o.key(exclude=drums)
    changes = []
    last = None
    for r in o.rows:
        if (r.tempo, r.speed) != last:
            changes.append((r.time, r.order_index, r.row, r.tempo, r.speed))
            last = (r.tempo, r.speed)
    w('# Payback song %d: analysis\n' % number)
    w('Generated by `stuntfox/tools/music/analyze.py` from the ROM (flavour: payback, i.e. as the game plays it).\n')
    w('- **Length:** %s (%d order positions, %d distinct patterns, %d rows played)' % (
        mmss(o.duration), len(s.order), len(s.patterns), len(o.rows)))
    w('- **Tempo:** %.0f BPM (4 rows a beat, 16 rows a bar, 64-row patterns = 4 bars at speed 6)' % o.bpm)
    w('- **Tempo/speed changes:** ' + '; '.join('%s order %d row %d: tempo %d speed %d (%.1f BPM)' % (
        mmss(t), oi, row, tp, sp, tp * 6.0 / sp) for t, oi, row, tp, sp in changes))
    w('- **Key (Krumhansl, pitched samples only):** %s (r = %.2f)' % key)
    w('- **Order list:** %s\n' % ' '.join(str(p) for p in s.order))

    # structure
    w('## Structure (one row per order position)\n')
    w('| pos | time | pattern | level dB | channel 0 | channel 1 | channel 2 | channel 3 | chords (per bar) |')
    w('|---|---|---|---|---|---|---|---|---|')
    audio = o.r.audio
    for oi, p in enumerate(s.order):
        t0 = o.time_of(oi)
        if t0 is None:
            continue
        t1 = o.time_of(oi + 1) if oi + 1 < len(s.order) and o.time_of(oi + 1) else o.duration
        seg = audio[int(t0 * o.rate):int(t1 * o.rate)]
        lvl = 10 * np.log10(np.mean(seg ** 2) + 1e-12)
        chans = []
        for c in range(4):
            ins = Counter(e.instrument for e in o.raw_notes if e.channel == c and e.order_index == oi)
            chans.append(' '.join('%d%s' % (k, '(%d)' % v if v > 1 else '') for k, v in ins.most_common(4)) or '-')
        ch = [c[2] for c in o.chords(t0, t1, beats=4, exclude=drums)]
        w('| %d | %s | %d | %.1f | %s | %s | %s | %s | %s |' % (oi, mmss(t0), p, lvl, *chans, ' '.join(ch)))
    w('\n(channel cells: sample numbers with note counts in that order position)\n')

    # channels
    w('## Channels\n')
    for c in range(4):
        ev = [e for e in o.raw_notes if e.channel == c]
        ins = Counter(e.instrument for e in ev)
        notes = [n for n in o.notes(channel=c) if n.ins not in drums]
        rng = ('%s .. %s' % (mix.note_name(min(n.midi for n in notes)), mix.note_name(max(n.midi for n in notes)))
               if notes else 'drums only')
        roles = Counter()
        for k, v in ins.items():
            roles[cls[k][0]] += v
        w('- **Channel %d** (%s): %d notes; samples %s; roles %s; pitched range %s' % (
            c, 'left' if c in (0, 3) else 'right', len(ev),
            ', '.join('%d x%d' % kv for kv in ins.most_common(8)),
            ', '.join('%s %d' % kv for kv in roles.most_common()), rng))
    w('')

    # samples
    w('## Samples\n')
    w('| # | role (heuristic) | seconds | loop | vol | measured pitch at C-2 (conf) | uses | channels | notes played | rows in bar |')
    w('|---|---|---|---|---|---|---|---|---|---|')
    for k, f in o.features.items():
        lab, u = cls[k]
        if f['chord']:
            pitch = 'chord %s' % ' '.join(mix.PC_NAMES[p] for p in f['chord'])
        elif f['tune'] is not None:
            pitch = '%s %+.0fc (%.2f)' % (mix.note_name(60 + f['tune']), 100 * (f['tune'] - round(f['tune'])),
                                           f['pitch_conf'])
        else:
            pitch = '-'
        if lab == 'unused':
            w('| %d | unused | %.2f | %s | %d | %s | 0 | | | |' % (k, f['seconds'], 'yes' if f['looped'] else 'no',
                                                                f['volume'], pitch))
            continue
        nts = ' '.join('%s%s' % (pbsong.note_name(p), 'x%d' % v if v > 1 else '') for p, v in u['periods'].most_common(5))
        rows = ' '.join('%d' % r for r, _ in sorted(u['rows16'].most_common(6)))
        w('| %d | %s | %.2f | %s | %d | %s | %d | %s | %s | %s |' % (
            k, lab, f['seconds'], 'yes' if f['looped'] else 'no', f['volume'], pitch, u['uses'],
            ' '.join('%d' % c for c, _ in u['channels'].most_common()), nts, rows))
    w('\n(notes played: tracker note names; sounding pitch = tracker note + the sample\'s measured offset from C4)\n')

    # hooks
    w('## Hooks (most repeated one-bar figures per channel, pitched samples)\n')
    bars = defaultdict(list)
    for e in o.raw_notes:
        if e.instrument in drums or e.volume == 0:
            continue
        m = pbsong.period_to_midi(e.period) + o.tune.get(e.instrument, 0)
        bars[(e.channel, e.order_index, e.row // 16)].append((e.row % 16, int(round(m)), e.instrument))
    for c in range(4):
        sig = Counter()
        where = defaultdict(list)
        for (ch, oi, b), ns in bars.items():
            if ch != c or len(ns) < 3:
                continue
            key_ = tuple((r, m) for r, m, _ in ns)
            sig[key_] += 1
            where[key_].append('%d.%d' % (oi, b))
        for figure, cnt in sig.most_common(3):
            if cnt < 2:
                continue
            ins = Counter(i for (ch, oi, b), ns in bars.items() if ch == c for _, _, i in ns
                          if tuple((r, m) for r, m, _ in ns) == figure)
            w('- ch%d x%d (samples %s), at pos.bar %s:  `%s`' % (
                c, cnt, ','.join(str(i) for i, _ in ins.most_common(3)), ' '.join(where[figure][:8]),
                '  '.join('r%d %s' % (r, mix.note_name(m)) for r, m in figure)))
    w('')

    # chords
    w('## Chord guesses per bar (all pitched notes)\n')
    seq = o.chords(exclude=drums, beats=4)
    prog = [c[2] for c in seq]
    loops = Counter(tuple(prog[i:i + 4]) for i in range(0, len(prog) - 3, 4))
    w('Most common 4-bar progressions: ' + '; '.join('%s (x%d)' % (' - '.join(p), n) for p, n in loops.most_common(4)))
    w('\nPitch-class weights over the song (pitched samples): ' + ', '.join(
        '%s %.0f%%' % (mix.PC_NAMES[i], 100 * v) for i, v in sorted(
            enumerate(o.pitch_classes(exclude=drums) / max(o.pitch_classes(exclude=drums).sum(), 1e-9)),
            key=lambda x: -x[1])[:7]))
    w('')
    return '\n'.join(L), o, cls


if __name__ == '__main__':
    text, _, _ = analyze(sys.argv[1], int(sys.argv[2]))
    print(text)
