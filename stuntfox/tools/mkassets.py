def font_tiles():
    """64 tiles (ASCII 32..95), 4bpp: colour 1 = text, 2 = shadow."""
    words = []
    for code in range(32, 96):
        rows = FONT.get(chr(code), ['00000'] * 7)
        pix = [[0] * 8 for _ in range(8)]
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == '1':
                    pix[y][x + 1] = 1
                    if pix[y + 1][x + 2] == 0:
                        pix[y + 1][x + 2] = 2
        for y in range(8):
            w = 0
            for x in range(8):
                w |= pix[y][x] << (4 * x)
            words.append(w)
    return words


def main(out):
    sin = [round(16384 * math.sin(2 * math.pi * i / 4096)) for i in range(4096)]
    with open(out, 'w') as f:
        f.write('/* generated by tools/mkassets.py */\n#include "../../src/gba.h"\n\n')
        f.write('const s16 sin_table[4096] = {\n')
        for i in range(0, 4096, 16):
            f.write('    ' + ', '.join(str(v) for v in sin[i:i + 16]) + ',\n')
        f.write('};\n\nconst u32 font_tiles[%d] = {\n' % (64 * 8))
        t = font_tiles()
        for i in range(0, len(t), 8):
            f.write('    ' + ', '.join('0x%08x' % v for v in t[i:i + 8]) + ',\n')
        f.write('};\n')


