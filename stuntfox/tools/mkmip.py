"""Smaller copies of Payback's ground tiles, made from the player's own Payback ROM.

Far off or high up, a pixel pair of the ground steps over more than one texel of a 32 x 32
tile, and a texel picked for each pair speckles (src/tex.c). There the game draws a tile's
averages over 2 x 2, 4 x 4 or 8 x 8 texels instead, each matched to the nearest of Payback's
colours. Only the tiles of the cells' and the decks' tops (each world's ctex and dtex: every
map's, since tile ids are global) get them, water too (from the image merge.c shows for it, as
tools/mkpal.py averages).

Output: C source with
    pb_mip[n][336]       per tile: its 16 x 16 averages (rows of 16), then 8 x 8, then 4 x 4
    pb_mipof[TILE_IDS]   tile id -> 1 + its row of pb_mip, 0: none
Pure Python, like the other build tools.
"""
import struct
import sys

import mkpal

N = 128                             # cells a side (tools/mkworld.py)
CTEX = 10                           # the world's sections: the tiles of the cells' tops
DTEX = 15                           # ... and of the decks' tops (when the world has them)
LEVELS = (1, 2, 3)                  # 2 x 2, 4 x 4 and 8 x 8 texels to one


def world_tops(world):
    """Tile ids of the cells' and the decks' tops, from the world mkworld.py made."""
    assert world[:4] in (b'SFW2', b'SFW3', b'SFW4'), 'not a world made by mkworld.py'   # (the same sections up to ctex)
    nsec = (struct.unpack_from('<I', world, 36)[0] - 36) // 4
    out = set()
    for k in (CTEX, DTEX) if nsec > DTEX else (CTEX,):
        at = struct.unpack_from('<I', world, 36 + 4 * k)[0]
        out |= {t for t in struct.unpack_from('<%dH' % (N * N), world, at) if 0 < t < mkpal.TILE_IDS}
    return out


def mips(rom, ids):
    pal = mkpal.palette(rom)
    solid = [(i, pal[i]) for i in range(1, 256)]
    near = {}

    def nearest(r, g, b):
        k = (r, g, b)
        if k not in near:
            near[k] = min(solid, key=lambda e: 3 * (e[1][0] - r) ** 2 + 4 * (e[1][1] - g) ** 2 +
                          2 * (e[1][2] - b) ** 2)[0]
        return near[k]
    out = []
    for t in ids:
        a = mkpal.WATER if t == mkpal.TEX_WATER else mkpal.TILE_BANK + t * 0x400
        px = [pal[p] for p in rom[a:a + 0x400]]   # (index 0 too: it is drawn, as its colour)
        blk = []
        for lv in LEVELS:
            s, w = 32 >> lv, 1 << lv
            for v in range(s):
                for u in range(s):
                    cell = [px[(v * w + y) * 32 + u * w + x] for y in range(w) for x in range(w)]
                    # (the average to a quarter of a level: fewer colours to look up)
                    blk.append(nearest(*(round(sum(c[k] for c in cell) * 4 / len(cell)) / 4
                                         for k in range(3))))
        out.append(blk)
    return out


def main(rom_path, worlds, out):
    """worlds: one world, or a list of them (the merged build's, one per map)"""
    rom = open(rom_path, 'rb').read() if isinstance(rom_path, str) else rom_path
    ids = sorted(set().union(*(world_tops(w) for w in (worlds if isinstance(worlds, list) else [worlds]))))
    blocks = mips(rom, ids)
    of = [0] * mkpal.TILE_IDS
    for k, t in enumerate(ids):
        of[t] = k + 1

    def arr(v):
        return ',\n    '.join(', '.join('%d' % x for x in v[i:i + 16]) for i in range(0, len(v), 16))
    with open(out, 'w') as f:
        f.write('/* generated by tools/mkmip.py from the player\'s Payback ROM */\n')
        f.write('#include "../../src/gba.h"\n')
        f.write('const u8 pb_mip[%d][336] = {\n' % max(1, len(blocks)))
        for b in blocks or [[0] * 336]:
            f.write('  {%s},\n' % arr(b))
        f.write('};\n')
        f.write('const u16 pb_mipof[%d] = {\n    %s};\n' % (len(of), arr(of)))
    return len(ids)


if __name__ == '__main__':
    print(main(sys.argv[1], open(sys.argv[2], 'rb').read(), sys.argv[3]))
